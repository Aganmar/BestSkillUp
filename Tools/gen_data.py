"""Generates a BestSkillUp Data_<Profession>.lua from Wowhead (WoW Forever) exports.

    python3 Tools/gen_data.py <Profession> <skillLine> <profession.json> <out.lua> [mining.json]

profession.json: {"professions": {"<Profession>": {"recipes": [row, ...]}}, "items": {id: item}}
    row  = [spellID, name, createsItemID, minMade, maxMade, [orange, yellow, green, grey], cat, learnedat,
            [[reagentID, qty], ...], [source, ...]]
    item = [name, quality, buyprice, sellprice, avgbuyout]
mining.json (Blacksmithing only): the same shape for Mining; its "Smelt ..." recipes become ns.Data.mining.

Export a profession from its Wowhead skill page (e.g. https://www.wowhead.com/forever/skill=185/cooking) by
mapping g_listviews.recipes.data and g_items into that shape in the browser console. Tools/data/ keeps the
exports used for the current data files.
"""
import json, sys, datetime

prof, skill_line, src, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
mining_src = sys.argv[5] if len(sys.argv) > 5 else None

D = json.load(open(src, encoding="utf-8"))
items = dict(D["items"])
mining = []
if mining_src:
    M = json.load(open(mining_src, encoding="utf-8"))
    for k, v in M["items"].items():
        items.setdefault(k, v)
    mining = [r for r in M["recipes"] if r[1].startswith("Smelt")]

# Wowhead's buyprice is a template value, not proof an item is vendor-sold: only these count as vendor items.
VENDOR_NAMES = {
    "Coarse Thread", "Fine Thread", "Silken Thread", "Heavy Silken Thread", "Rune Thread", "Bleach",
    "Red Dye", "Blue Dye", "Green Dye", "Gray Dye", "Yellow Dye", "Black Dye", "Purple Dye", "Orange Dye", "Pink Dye",
    "Empty Vial", "Leaded Vial", "Crystal Vial", "Imbued Vial", "Weak Flux", "Strong Flux", "Elemental Flux",
    "Mild Spices", "Hot Spices", "Soothing Spices", "Salt", "Simple Flour", "Refreshing Spring Water", "Ice Cold Milk",
    "Engineer's Ink", "Blank Parchment", "Wooden Stock", "Heavy Stock", "Simple Wood", "Star Wood", "Coal",
    # Cooking
    "Shiny Red Apple", "Melon Juice", "Moonberry Juice", "Sweet Nectar", "Morning Glory Dew", "Rhapsody Malt",
    "Skin of Dwarven Stout", "Holiday Spices", "Holiday Spirits",
    # First Aid
    "Flagon of Dwarven Honeymead", "Thunder Ale", "Bottle of Dalaran Noir",
    # Enchanting
    "Copper Rod", "Maple Seed", "Stranglethorn Seed", "Red-speckled Mushroom",
}

def group(src):
    s = set(src or [])
    if 6 in s: return "trainer"
    if 5 in s: return "vendor"
    if 2 in s: return "drop"
    if 4 in s: return "quest"
    return "other"

def thresholds(r):
    c = r[5]
    gr = c[3]; g = c[2] or gr; y = c[1] or g
    o = c[0] or r[7] or y or 1
    if not c[0] and not r[9] and (r[7] or 0) <= 20:
        o = 1  # starter recipes known from skill 1
    return o, y, g, gr

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def recipe_line(r):
    o, y, g, gr = thresholds(r)
    reag = ",".join(f"{i},{q}" for i, q in r[8])
    # Wowhead gives some recipes that make an item a count of 0 (oils, wands, kits): they make one.
    lo, hi = r[3], r[4]
    if r[2] and not lo: lo = hi = 1
    return f"[{r[0]}]={{{lua_str(r[1])},{r[2] or 0},{lo},{hi},{o},{y},{g},{gr},\"{group(r[9])}\",{{{reag}}}}},"

# Recipes that can never give a point (grey at 0, e.g. unfinished entries) are left out.
recipes = [r for r in D["professions"][prof]["recipes"] if r[5][3] > 0]

used = set()
for r in recipes + mining:
    if r[2]: used.add(str(r[2]))
    for i, _ in r[8]: used.add(str(i))

lines = [
    "-- Generated by Tools/gen_data.py from Wowhead (WoW Forever) on " + datetime.date.today().isoformat() + ". Do not edit by hand.",
    "-- recipe = { name, outputItemID, minMade, maxMade, orange, yellow, green, grey, source, { reagentID, qty, ... } }",
    "-- item   = { name, quality, vendorSellPrice, wowheadAvgBuyout }",
    "local _, ns = ...",
    "ns.AddProfessionData({",
    f'  profession = {lua_str(prof)}, skillLine = {skill_line},' + (" miningSkillLine = 186," if mining else ""),
    "  recipes = {",
]
lines += ["    " + recipe_line(r) for r in sorted(recipes, key=lambda r: r[0])]
lines += ["  },"]
if mining:
    lines += ["  mining = {"]
    lines += ["    " + recipe_line(r) for r in sorted(mining, key=lambda r: r[0])]
    lines += ["  },"]
lines += ["  items = {"]
for k in sorted(used, key=int):
    it = items.get(k)
    if not it: continue
    lines.append(f"    [{k}]={{{lua_str(it[0])},{it[1]},{it[3]},{it[4]}}},")
lines += ["  },", "  -- Fallback vendor prices (Auctionator's own vendor cache is used first).", "  vendor = {"]
for k in sorted(used, key=int):
    it = items.get(k)
    if it and it[0] in VENDOR_NAMES and it[2] > 0:
        lines.append(f"    [{k}]={it[2]}, -- {it[0]}")
lines += ["  },", "})", ""]
open(out, "w", newline="\n", encoding="utf-8").write("\n".join(lines))
print(f"{prof}: {len(recipes)} recipes, {len(mining)} smelts, {len(used)} items -> {out}", file=sys.stderr)
